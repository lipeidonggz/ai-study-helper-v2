MAX_SOURCE_BYTES = 20 * 1024 * 1024
MAX_SOURCE_SIZE_LABEL = f"{MAX_SOURCE_BYTES // (1024 * 1024)} MiB"
MAX_REDIRECTS = 5
RETRY_DELAYS_SECONDS = (1.0, 4.0)
HTTP_CONNECT_TIMEOUT_SECONDS = 10.0
HTTP_TOTAL_TIMEOUT_SECONDS = 60.0

_META_CHARSET_PATTERN = re.compile(
    rb"""<meta[^>]+charset\s*=\s*["']?\s*([a-zA-Z0-9._-]+)""",
    re.IGNORECASE,
)
_CONTENT_TYPE_CHARSET_PATTERN = re.compile(
    r"charset\s*=\s*[\"']?([a-zA-Z0-9._-]+)",
    re.IGNORECASE,
)


@dataclass(slots=True)
class AcquiredSource:
    """一次来源获取的统一内存结果，供后续提取使用。"""

    artifact: SourceArtifact
    raw_bytes: bytes
    decoded_html: str


@dataclass(slots=True)
class FetchedResponse:
    """URL 适配器返回的最终 HTTP 响应。"""

    url: str
    status_code: int
    headers: dict[str, str]
    body: bytes
    warnings: list[str]


class UrlFetcher(Protocol):
    """URL 获取适配器的最小协议。"""

    async def fetch(self, url: str) -> FetchedResponse:
        """Fetch one public HTML source and return its final response."""
        ...


class ArtifactStore:
    """创建隔离的入库 job，并原子写入预览与正式派生 artifact。"""

    def __init__(self, data_root: Path) -> None:
        self.data_root = data_root.resolve()
        self.jobs_root = self.data_root / "jobs"
        self.jobs_root.mkdir(parents=True, exist_ok=True)

    def create_job(self) -> tuple[str, Path]:
        """创建不可复用的 job 目录并返回稳定格式的 job ID。"""

        job_id = uuid4().hex
        job_dir = self.jobs_root / job_id
        job_dir.mkdir(parents=True, exist_ok=False)
        return job_id, job_dir

    def job_dir(self, job_id: str) -> Path:
        """解析并校验 job ID，阻止调用者构造越界路径。"""

        # Job IDs are generated by this process, but validate before joining to
        # keep a future caller from turning persisted input into path traversal.
        if not re.fullmatch(r"[0-9a-f]{32}", job_id):
            raise IngestFailure("invalid_job_id", "invalid job identifier", 400)
        return self.jobs_root / job_id

    def write_raw(self, job_id: str, relative_name: str, data: bytes) -> str:
        """原子写入 job artifact，并返回相对 data root 的引用。"""

        target = self.job_dir(job_id) / relative_name
        target.parent.mkdir(parents=True, exist_ok=True)
        self._atomic_write(target, data)
        return target.relative_to(self.data_root).as_posix()

    def write_json(self, job_id: str, relative_name: str, data: str) -> str:
        """把 UTF-8 JSON 作为不可变 job artifact 原子写入。"""

        return self.write_raw(job_id, relative_name, data.encode("utf-8"))

    def read_text(self, job_id: str, relative_name: str) -> str:
        """读取固定 job 内的文本 artifact，并映射缺失错误。"""

        return self.read_ref_text(
            f"jobs/{job_id}/{relative_name}",
            missing_code="job_artifact_missing",
        )

    def read_ref_text(
        self,
        artifact_ref: str,
        *,
        missing_code: str = "artifact_missing",
    ) -> str:
        """只允许读取 data root 内的相对 artifact ref。"""

        target = self.ref_path(artifact_ref, missing_code=missing_code)
        try:
            return target.read_text(encoding="utf-8")
        except OSError as error:
            raise IngestFailure(
                "artifact_unreadable",
                f"could not read artifact {artifact_ref}: {error}",
                500,
            ) from error

    def ref_path(
        self,
        artifact_ref: str,
        *,
        missing_code: str = "artifact_missing",
        must_be_file: bool = True,
    ) -> Path:
        """解析 data root 内的 ref，并拒绝越界和缺失路径。"""

        relative_path = Path(artifact_ref)
        if relative_path.is_absolute():
            raise IngestFailure("invalid_artifact_ref", "artifact ref must be relative", 500)
        target = (self.data_root / relative_path).resolve()
        if not target.is_relative_to(self.data_root):
            raise IngestFailure("invalid_artifact_ref", "artifact ref escapes data root", 500)
        if (must_be_file and not target.is_file()) or (not must_be_file and not target.exists()):
            raise IngestFailure(
                missing_code,
                f"required artifact is missing: {artifact_ref}",
                404,
            )
        return target

    @staticmethod
    def _atomic_write(target: Path, data: bytes) -> None:
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary_path: Path | None = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="wb",
                dir=target.parent,
                prefix=f".{target.name}.",
                suffix=".tmp",
                delete=False,
            ) as temporary:
                temporary.write(data)
                temporary.flush()
                os.fsync(temporary.fileno())
                temporary_path = Path(temporary.name)
            os.replace(temporary_path, target)
        finally:
            if temporary_path and temporary_path.exists():
                temporary_path.unlink(missing_ok=True)


def _utc_now() -> str:
    return datetime.now(UTC).isoformat()


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _decode_html(raw: bytes, content_type: str | None = None) -> tuple[str, str]:
    candidates: list[str] = []
    if content_type:
        match = _CONTENT_TYPE_CHARSET_PATTERN.search(content_type)
        if match:
            candidates.append(match.group(1))
    if raw.startswith(b"\xef\xbb\xbf"):
        candidates.append("utf-8-sig")
    elif raw.startswith((b"\xff\xfe", b"\xfe\xff")):
        candidates.append("utf-16")
    meta_match = _META_CHARSET_PATTERN.search(raw[:8192])
    if meta_match:
        candidates.append(meta_match.group(1).decode("ascii", errors="ignore"))
    candidates.extend(["utf-8", "gb18030", "big5"])

    seen: set[str] = set()
    for candidate in candidates:
        normalized = candidate.strip().lower()
        if not normalized or normalized in seen:
            continue
        seen.add(normalized)
        try:
            return raw.decode(normalized), normalized
        except (LookupError, UnicodeDecodeError):
            continue

    best = from_bytes(raw).best()
    if best and best.encoding:
        return str(best), best.encoding
    raise IngestFailure(
        "charset_detection_failed",
        "could not determine the HTML character encoding",
        422,
    )


async def acquire_local_source(
    source_value: str,
    *,
    store: ArtifactStore,
) -> tuple[str, AcquiredSource]:
    """读取并留痕一个本地 HTML 文件。"""

    path = Path(source_value).expanduser()
    try:
        resolved = path.resolve(strict=True)
    except FileNotFoundError as error:
        raise IngestFailure("source_not_found", "local HTML file does not exist", 404) from error
    except OSError as error:
        raise IngestFailure(
            "source_unreadable", f"cannot resolve local file: {error}", 422
        ) from error

    if not resolved.is_file() or resolved.suffix.lower() not in {".html", ".htm"}:
        raise IngestFailure(
            "unsupported_source",
            "only local .html and .htm files are supported",
            422,
        )
    try:
        size = resolved.stat().st_size
    except OSError as error:
        raise IngestFailure("source_unreadable", f"cannot stat local file: {error}", 422) from error
    if size > MAX_SOURCE_BYTES:
        raise IngestFailure(
            "source_too_large",
            f"local HTML exceeds the {MAX_SOURCE_BYTES // (1024 * 1024)} MiB limit",
            413,
        )
    try:
        raw = await asyncio.to_thread(resolved.read_bytes)
    except OSError as error:
        raise IngestFailure("source_unreadable", f"cannot read local file: {error}", 422) from error
    if not raw:
        raise IngestFailure("empty_source", "local HTML file is empty", 422)

    job_id, _ = store.create_job()
    raw_ref = store.write_raw(job_id, "source.html", raw)
    charset_text, charset = _decode_html(raw, None)
    artifact = SourceArtifact(
        source_kind="file",
        source_key=resolved.as_posix(),
        source_uri=source_value,
        media_type="text/html",
        raw_artifact_ref=raw_ref,
        content_hash=_sha256(raw),
        raw_byte_length=len(raw),
        fetched_at=_utc_now(),
        final_url=None,
        http_status=None,
        acquisition_mode="file",
        charset=charset,
    )
    return job_id, AcquiredSource(artifact, raw, charset_text)


def _normalize_url(url: str) -> str:
    parts = urlsplit(url.strip())
    scheme = parts.scheme.lower()
    if scheme not in {"http", "https"}:
        raise IngestFailure("invalid_url", "URL must use http or https", 422)
    if parts.username or parts.password:
        raise IngestFailure("invalid_url", "URL credentials are not allowed", 422)
    hostname = parts.hostname
    if not hostname:
        raise IngestFailure("invalid_url", "URL must include a hostname", 422)
    try:
        port = parts.port
    except ValueError as error:
        raise IngestFailure("invalid_url", "URL contains an invalid port", 422) from error
    netloc = hostname
    if ":" in hostname and not hostname.startswith("["):
        netloc = f"[{hostname}]"
    if port:
        netloc = f"{netloc}:{port}"
    return urlunsplit((scheme, netloc, parts.path or "/", parts.query, ""))


def _resolve_addresses(hostname: str, port: int) -> list[str]:
    try:
        records = socket.getaddrinfo(hostname, port, type=socket.SOCK_STREAM)
    except socket.gaierror as error:
        raise IngestFailure(
            "dns_resolution_failed", "could not resolve source hostname", 502
        ) from error
    return sorted({str(record[4][0]) for record in records})


async def _validate_public_url(
    url: str,
    resolver: Callable[[str, int], list[str]],
) -> str:
    normalized = _normalize_url(url)
    parts = urlsplit(normalized)
    assert parts.hostname is not None
    hostname = parts.hostname
    lowered = hostname.rstrip(".").lower()
    if lowered in {"localhost", "localhost.localdomain"} or lowered.endswith(".local"):
        raise IngestFailure("ssrf_blocked", "local network URLs are not allowed", 422)
    try:
        literal_address = ipaddress.ip_address(hostname)
    except ValueError:
        literal_address = None
    if literal_address is not None and not literal_address.is_global:
        raise IngestFailure(
            "ssrf_blocked",
            "source URL uses a non-public IP address",
            422,
        )
    port = parts.port or (443 if parts.scheme == "https" else 80)
    addresses = await asyncio.to_thread(resolver, hostname, port)
    if not addresses:
        raise IngestFailure("dns_resolution_failed", "source hostname has no addresses", 502)
    for address in addresses:
        ip = ipaddress.ip_address(address)
        if not ip.is_global:
            raise IngestFailure(
                "ssrf_blocked",
                "source hostname resolves to a non-public address",
                422,
            )
    return normalized


class HttpUrlFetcher:
    """获取公开静态／SSR HTML；不携带 Cookie，也不执行页面脚本。"""

    def __init__(
        self,
        *,
        transport: httpx.AsyncBaseTransport | None = None,
        resolver: Callable[[str, int], list[str]] = _resolve_addresses,
    ) -> None:
        self._transport = transport
        self._resolver = resolver

    async def fetch(self, url: str) -> FetchedResponse:
        """校验每一跳公开地址后读取 HTML，并返回最终响应。"""

        current = _normalize_url(url)
        warnings = ["dns_rebinding_not_pinned"]
        timeout = httpx.Timeout(
            HTTP_TOTAL_TIMEOUT_SECONDS,
            connect=HTTP_CONNECT_TIMEOUT_SECONDS,
        )
        async with httpx.AsyncClient(
            transport=self._transport,
            follow_redirects=False,
            timeout=timeout,
            trust_env=False,
            headers={"User-Agent": "ai-study-helper/0.1"},
        ) as client:
            for redirect_count in range(MAX_REDIRECTS + 1):
                current = await _validate_public_url(current, self._resolver)
                response = await self._request_with_retry(client, current)
                if response.status_code in range(300, 400):
                    location = response.headers.get("location")
                    if not location:
                        raise IngestFailure(
                            "invalid_redirect",
                            "source redirect has no Location header",
                            502,
                        )
                    if redirect_count >= MAX_REDIRECTS:
                        raise IngestFailure(
                            "too_many_redirects",
                            f"source exceeded {MAX_REDIRECTS} redirects",
                            422,
                        )
                    current = _normalize_url(str(httpx.URL(current).join(location)))
                    continue
                if response.status_code < 200 or response.status_code >= 300:
                    code = (
                        "http_access_denied"
                        if response.status_code in {401, 403}
                        else "http_status_error"
                    )
                    raise IngestFailure(
                        code,
                        f"source returned HTTP {response.status_code}",
                        502,
                    )
                content_type = response.headers.get("content-type", "")
                if not content_type.lower().startswith("text/html"):
                    raise IngestFailure(
                        "unsupported_media_type",
                        "URL response is not text/html",
                        422,
                    )
                if not response.body:
                    raise IngestFailure("empty_source", "URL response body is empty", 422)
                return FetchedResponse(
                    url=current,
                    status_code=response.status_code,
                    headers=response.headers,
                    body=response.body,
                    warnings=warnings,
                )
        raise IngestFailure("too_many_redirects", "redirect limit reached", 422)

    @staticmethod
    async def _request_with_retry(
        client: httpx.AsyncClient,
        url: str,
    ) -> FetchedResponse:
        last_error: Exception | None = None
        for attempt in range(len(RETRY_DELAYS_SECONDS) + 1):
            try:
                async with client.stream("GET", url) as response:
                    content_length = response.headers.get("content-length")
                    if content_length and int(content_length) > MAX_SOURCE_BYTES:
                        raise IngestFailure(
                            "source_too_large",
                            f"URL response exceeds the {MAX_SOURCE_SIZE_LABEL} limit",
                            413,
                        )
                    if (
                        response.status_code in {408, 429} or response.status_code >= 500
                    ) and attempt < len(RETRY_DELAYS_SECONDS):
                        await response.aread()
                        await asyncio.sleep(RETRY_DELAYS_SECONDS[attempt])
                        continue
                    chunks: list[bytes] = []
                    size = 0
                    async for chunk in response.aiter_bytes():
                        size += len(chunk)
                        if size > MAX_SOURCE_BYTES:
                            raise IngestFailure(
                                "source_too_large",
                                f"URL response exceeds the {MAX_SOURCE_SIZE_LABEL} limit",
                                413,
                            )
                        chunks.append(chunk)
                    return FetchedResponse(
                        url=url,
                        status_code=response.status_code,
                        headers=dict(response.headers),
                        body=b"".join(chunks),
                        warnings=[],
                    )
            except IngestFailure:
                raise
            except (httpx.TimeoutException, httpx.NetworkError) as error:
                last_error = error
                if attempt < len(RETRY_DELAYS_SECONDS):
                    await asyncio.sleep(RETRY_DELAYS_SECONDS[attempt])
                    continue
                break
        raise IngestFailure(
            "network_error",
            f"could not fetch URL: {last_error}",
            502,
            retryable=True,
        )


async def acquire_url_source(
    source_value: str,
    *,
    store: ArtifactStore,
    fetcher: UrlFetcher | None = None,
) -> tuple[str, AcquiredSource]:
    """通过受限 HTTP 适配器获取 URL，并把原始响应留痕为 artifact。"""

    fetched = await (fetcher or HttpUrlFetcher()).fetch(source_value)
    if len(fetched.body) > MAX_SOURCE_BYTES:
        raise IngestFailure(
            "source_too_large",
            f"URL response exceeds the {MAX_SOURCE_BYTES // (1024 * 1024)} MiB limit",
            413,
        )

    job_id, _ = store.create_job()
    raw_ref = store.write_raw(job_id, "source.html", fetched.body)
    decoded, charset = _decode_html(fetched.body, fetched.headers.get("content-type"))
    artifact = SourceArtifact(
        source_kind="url",
        source_key=fetched.url,
        source_uri=source_value,
        media_type="text/html",
        raw_artifact_ref=raw_ref,
        content_hash=_sha256(fetched.body),
        raw_byte_length=len(fetched.body),
        fetched_at=_utc_now(),
        final_url=fetched.url,
        http_status=fetched.status_code,
        acquisition_mode="http",
        charset=charset,
        warnings=fetched.warnings,
    )
    return job_id, AcquiredSource(artifact, fetched.body, decoded)
